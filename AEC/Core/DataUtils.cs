        // 二分查找
        public static short FindNearestIndexFromOrderedList(double value, double[] list)
        {
            Debug.Assert(list != null && list.Length > 0);

            if (value <= list[0])
            {
                return 0;
            }
            else if (value >= list[list.Length - 1])
            {
                return (short)(list.Length - 1);
            }
            else
            {
                short left = 0;
                short right = (short)(list.Length - 1);
                while (left < right)
                {
                    short mid = (short)((left + right) / 2);
                    if (value < list[mid])
                    {
                        right = mid;
                    }
                    else if (value > list[mid])
                    {
                        left = mid;
                    }
                    else
                    {
                        return mid;
                    }

                    if (right - left == 1)
                    {
                        break;
                    }
                }

                double leftDiff = value - list[left];
                double rightDiff = list[right] - value;

                if (leftDiff <= rightDiff)
                {
                    return left;
                }
                else
                {
                    return right;
                }
            }
        }

        public static short FindNearestIndexFromOrderedList(int value, int[] list)
        {
            Debug.Assert(list != null && list.Length > 0);

            if (value <= list[0])
            {
                return 0;
            }
            else if (value >= list[list.Length - 1])
            {
                return (short)(list.Length - 1);
            }
            else
            {
                short left = 0;
                short right = (short)(list.Length - 1);
                while (left < right)
                {
                    short mid = (short)((left + right) / 2);
                    if (value < list[mid])
                    {
                        right = mid;
                    }
                    else if (value > list[mid])
                    {
                        left = mid;
                    }
                    else
                    {
                        return mid;
                    }

                    if (right - left == 1)
                    {
                        break;
                    }
                }

                int leftDiff = value - list[left];
                int rightDiff = list[right] - value;

                if (leftDiff <= rightDiff)
                {
                    return left;
                }
                else
                {
                    return right;
                }
            }
        }

